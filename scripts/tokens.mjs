#!/usr/bin/env node
// HOUSE LIGHTS — the ONE token source. Emits web/src/styles/tokens.css and lib/theme/tokens.dart.
// CI runs `node scripts/tokens.mjs && git diff --exit-code` on both outputs: never hand-edit them.
import { writeFileSync, mkdirSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const auditorium = {
  bg: '#07060A',
  bgElevated: '#120E15',
  surface: '#1B1620',
  surface2: '#26202B',
  ink: '#F3E9DA',
  inkMuted: '#A89C8C',
  inkFaint: '#8C8276',
  accent: '#FFC56E',
  accentInk: '#1A1006',
  accent2: '#A3252F',
  accent2Lit: '#E0525C',
  success: '#5FD48A',
  warning: '#F5A05F',
  danger: '#E5484D',
  border: '#2A2330',
  borderStrong: '#3D3446',
  focus: '#FFD68A',
  skyDawn: '#3A2A2E',
  skyDay: '#2A2E3A',
  skyDusk: '#2F2438',
  skyNight: '#0B0A10',
}

const matinee = {
  bg: '#F1E8D8',
  bgElevated: '#F8F2E6',
  surface: '#E8DECB',
  surface2: '#DDD1BC',
  ink: '#2A2226',
  inkMuted: '#5E5350',
  inkFaint: '#605651',
  accent: '#7F4800',
  accentInk: '#FFF6E6',
  accent2: '#A3252F',
  accent2Lit: '#A3252F',
  success: '#186639',
  warning: '#8A4B00',
  danger: '#A8231C',
  border: '#D6CAB5',
  borderStrong: '#B9AB93',
  focus: '#7A4A00',
  skyDawn: '#F5C9A8',
  skyDay: '#C9D6E8',
  skyDusk: '#C8A9D6',
  skyNight: '#1A1622',
}

const text = { xs: 12, sm: 14, base: 16, lg: 18, xl: 22, '2xl': 28, '3xl': 36, '4xl': 64, '5xl': 144 }
const space = [4, 8, 12, 16, 20, 24, 32, 40, 48, 64, 80, 96]
const radius = { sm: 4, md: 8, lg: 12, xl: 20, full: 9999 }
const dur = { fast: 120, base: 240, slow: 480, house: 900 }
const ease = {
  out: [0.22, 1, 0.36, 1],
  inOut: [0.65, 0, 0.35, 1],
  house: [0.7, 0, 0.3, 1],
}
const spring = { stiffness: 380, damping: 32, mass: 1 }
const layout = { pageMax: 1280, gutter: 24, marginPhone: 20, targetMin: 44, gateHeight: 56, gateHeightDesktop: 40, controlsIdle: 2400 }
const grain = { auditorium: 0.04, matinee: 0.03 }

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-z])(\d)/g, '$1-$2').toLowerCase()
const cssVar = (k) => `--${kebab(k)}`

// ------------------------------------------------------------------ CSS
const palette = (p, indent) =>
  Object.entries(p)
    .filter(([k]) => !k.startsWith('sky'))
    .map(([k, v]) => `${indent}${cssVar(k)}: ${v};`)
    .join('\n')

const css = `/* web/src/styles/tokens.css — GENERATED by scripts/tokens.mjs. Do not edit. */
:root {
  /* ---- Auditorium (default, dark) ---- */
${palette(auditorium, '  ')}

  /* semantic / derived */
  --picture-bg: #000000;
  --wall-glow: radial-gradient(60% 60% at 50% 50%, color-mix(in oklch, var(--focus) 6%, transparent), transparent);
  --bulb-halo: 0 0 6px 1px color-mix(in oklch, var(--accent) 55%, transparent);
  --booth-glass: color-mix(in oklch, var(--bg-elevated) 78%, transparent);
  --glass-blur: 24px;
  --sky-dawn: ${auditorium.skyDawn}; --sky-day: ${auditorium.skyDay}; --sky-dusk: ${auditorium.skyDusk}; --sky-night: ${auditorium.skyNight};
  --house: 1;                 /* 1 = house up, 0 = dark */
  --grain-opacity: ${grain.auditorium};      /* lobby + sheets only; 0 in the auditorium */

  /* ---- Typography ---- */
  --font-display: "Big Shoulders Display Variable", "Big Shoulders Display", Impact, "Arial Narrow", sans-serif;
  --font-body: "Geist Variable", Geist, system-ui, "Segoe UI", sans-serif;
  --font-mono: "Geist Mono Variable", "Geist Mono", ui-monospace, Consolas, monospace;
  --text-xs: 0.75rem;  --text-sm: 0.875rem; --text-base: 1rem;
  --text-lg: 1.125rem; --text-xl: 1.375rem; --text-2xl: 1.75rem; --text-3xl: 2.25rem;
  --text-4xl: clamp(3rem, 6vw, 4rem);
  --text-5xl: clamp(5rem, 14vw, 9rem);
  --leading-tight: 1.05;
  --leading-body: 1.5;
  --tracking-display: 0.06em;
  --tracking-display-lg: 0.02em;
  --tracking-label: 0.08em;

  /* ---- Spacing ---- */
${space.map((v, i) => `  --space-${i + 1}: ${v}px;`).join('\n')}

  /* ---- Radius ---- */
${Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n')}

  /* ---- Elevation (one light source, above and behind) ---- */
  --shadow-1: inset 0 1px 0 rgba(255,255,255,.04), 0 2px 6px rgba(0,0,0,.5);
  --shadow-2: inset 0 1px 0 rgba(255,255,255,.05), 0 8px 24px rgba(0,0,0,.55);
  --shadow-3: inset 0 1px 0 rgba(255,255,255,.06), 0 24px 56px rgba(0,0,0,.65);

  /* ---- Motion ---- */
${Object.entries(dur).map(([k, v]) => `  --dur-${k}: ${v}ms;`).join('\n')}
${Object.entries(ease).map(([k, v]) => `  --ease-${kebab(k)}: cubic-bezier(${v.join(', ')});`).join('\n')}
  --ease-spring: linear(0, 0.006, 0.025 2.8%, 0.101 6.1%, 0.539 18.9%, 0.721 25.3%, 0.849 31.5%, 0.937 38.1%, 0.968 41.8%, 0.991 45.7%, 1.006 50.1%, 1.012 55.4%, 1.011 62.6%, 1.006 71.7%, 1);
  --spring-stiffness: ${spring.stiffness}; --spring-damping: ${spring.damping}; --spring-mass: ${spring.mass};

  /* ---- Layout ---- */
  --page-max: ${layout.pageMax}px; --gutter: ${layout.gutter}px; --margin-phone: ${layout.marginPhone}px;
  --target-min: ${layout.targetMin}px; --gate-height: ${layout.gateHeight}px; --controls-idle: ${layout.controlsIdle}ms;

  color-scheme: dark;
}

/* Matinee — Lobby, Booth, Ticket Office only; never while a file is open */
[data-theme="matinee"] {
${palette(matinee, '  ')}
  --sky-dawn: ${matinee.skyDawn}; --sky-day: ${matinee.skyDay}; --sky-dusk: ${matinee.skyDusk}; --sky-night: ${matinee.skyNight};
  --bulb-halo: none;
  --shadow-1: 0 1px 2px rgba(42,34,38,.12);
  --shadow-2: 0 6px 18px rgba(42,34,38,.16);
  --shadow-3: 0 18px 40px rgba(42,34,38,.22);
  --grain-opacity: ${grain.matinee};
  color-scheme: light;
}

@property --house { syntax: "<number>"; inherits: true; initial-value: 1; }

@media (prefers-reduced-motion: reduce) {
  :root { --dur-house: 240ms; --ease-house: var(--ease-in-out); --ease-spring: var(--ease-out); }
}
`

// ------------------------------------------------------------------ Dart
const argb = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`
const dartPalette = (name, p) =>
  `  static const ${name} = HousePalette(\n${Object.entries(p)
    .map(([k, v]) => `    ${k}: ${argb(v)},`)
    .join('\n')}\n  );`

const dart = `// lib/theme/tokens.dart — GENERATED by scripts/tokens.mjs. Do not edit.
// ignore_for_file: public_member_api_docs
import 'package:flutter/animation.dart';
import 'package:flutter/painting.dart';

/// One room's colours. Auditorium is the default and the only palette during playback.
class HousePalette {
${Object.keys(auditorium).map((k) => `  final Color ${k};`).join('\n')}
  const HousePalette({
${Object.keys(auditorium).map((k) => `    required this.${k},`).join('\n')}
  });
}

abstract final class Tokens {
${dartPalette('auditorium', auditorium)}

${dartPalette('matinee', matinee)}

  // Auditorium shorthands (playback is always Auditorium).
${Object.entries(auditorium).map(([k, v]) => `  static const ${k} = ${argb(v)};`).join('\n')}
  static const pictureBg = Color(0xFF000000);

  static const grainAuditorium = ${grain.auditorium};
  static const grainMatinee = ${grain.matinee};

  // ---- Typography ----
  static const fontDisplay = 'Big Shoulders Display';
  static const fontBody = 'Geist';
  static const fontMono = 'Geist Mono';
  static const fontSubtitle = 'Noto Sans';
  static const textScale = <String, double>{
${Object.entries(text).map(([k, v]) => `    '${k}': ${v.toFixed(1)},`).join('\n')}
  };
${Object.entries(text).map(([k, v]) => `  static const text${k === '2xl' ? '2Xl' : k === '3xl' ? '3Xl' : k === '4xl' ? '4Xl' : k === '5xl' ? '5Xl' : k[0].toUpperCase() + k.slice(1)} = ${v.toFixed(1)};`).join('\n')}
  static const leadingTight = 1.05;
  static const leadingBody = 1.5;
  static const trackingDisplay = 0.06;
  static const trackingDisplayLg = 0.02;
  static const trackingLabel = 0.08;

  // ---- Spacing ----
${space.map((v, i) => `  static const space${i + 1} = ${v.toFixed(1)};`).join('\n')}

  // ---- Radius ----
${Object.entries(radius).map(([k, v]) => `  static const radius${k[0].toUpperCase() + k.slice(1)} = ${v.toFixed(1)};`).join('\n')}

  // ---- Motion ----
${Object.entries(dur).map(([k, v]) => `  static const dur${k[0].toUpperCase() + k.slice(1)} = Duration(milliseconds: ${v});`).join('\n')}
${Object.entries(ease).map(([k, v]) => `  static const ease${k[0].toUpperCase() + k.slice(1)} = Cubic(${v.join(', ')});`).join('\n')}
  static const spring = SpringDescription(mass: ${spring.mass}, stiffness: ${spring.stiffness}, damping: ${spring.damping});

  // ---- Layout ----
${Object.entries(layout).map(([k, v]) => `  static const ${k} = ${k === 'controlsIdle' ? `Duration(milliseconds: ${v})` : v.toFixed(1)};`).join('\n')}

  // ---- Elevation (every shadow falls down) ----
  static const shadow1 = [
    BoxShadow(color: Color(0x80000000), offset: Offset(0, 2), blurRadius: 6),
  ];
  static const shadow2 = [
    BoxShadow(color: Color(0x8C000000), offset: Offset(0, 8), blurRadius: 24),
  ];
  static const shadow3 = [
    BoxShadow(color: Color(0xA6000000), offset: Offset(0, 24), blurRadius: 56),
  ];
}
`

const write = (rel, body) => {
  const p = join(root, rel)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, body.replace(/\r\n/g, '\n'))
}
write('web/src/styles/tokens.css', css)
write('lib/theme/tokens.dart', dart)
// Keep the Dart output in `dart format` shape so the format gate and the drift gate agree.
spawnSync('dart', ['format', join(root, 'lib/theme/tokens.dart')], { stdio: 'ignore', shell: process.platform === 'win32' })
console.log('tokens: wrote web/src/styles/tokens.css and lib/theme/tokens.dart')
